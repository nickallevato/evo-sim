"""Per-person argument pages from the math map (read-only over the map; writes docs/people/).

Usage (repo root): research/.venv/bin/python -I research/tools/people_pages.py [MAPDIR ...]
  default MAPDIR = docs/research/math/sources. Each map's objects come from the objects.yaml
  beside its sources/ folder (docs/research/math/objects.yaml for the real map).
Writes docs/people/<slug>.md (every argument the person made: quote, locator, RH tag, steps,
math objects with status and record) and docs/people/README.md (index). Speakers resolve through
docs/research/math/people.yaml; unknown speakers are listed in the index as "unregistered".
"""
import collections
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs/people"


def registry():
    reg = yaml.safe_load((ROOT / "docs/research/math/people.yaml").read_text())["people"]
    alias = {}
    for slug, p in reg.items():
        for a in p["aliases"] + [p["name"], slug]:
            alias[a.lower()] = slug
    return reg, alias


def parse_map(path):
    lines = path.read_text().splitlines()
    title = next((l.lstrip("# ").strip() for l in lines if l.startswith("# ")), path.stem)
    hdr, rows = None, []
    for l in lines:
        if not l.startswith("|"):
            continue
        cells = [c.strip() for c in l.strip().strip("|").split("|")]
        if hdr is None and "Speaker" in cells:
            hdr = [c.lower() for c in cells]
            continue
        if hdr and set(l) <= set("|-: "):
            continue
        if hdr and len(cells) >= len(hdr):
            rows.append(dict(zip(hdr, cells)))
    return title, rows


def objects_for(mapdir):
    f = mapdir.parent / "objects.yaml"
    if not f.exists():
        return {}
    data = yaml.safe_load(f.read_text()) or {}
    objs = data["objects"] if isinstance(data, dict) else data
    return {o["id"]: o for o in objs or []}


def main(argv):
    dirs = [Path(a) for a in argv] or [ROOT / "docs/research/math/sources"]
    reg, alias = registry()
    per = collections.defaultdict(list)
    unknown = collections.Counter()
    for d in dirs:
        d = d if d.is_absolute() else ROOT / d
        objs = objects_for(d)
        for m in sorted(d.glob("*.md")):
            title, rows = parse_map(m)
            for r in rows:
                sp = r.get("speaker", "")
                mm = re.match(r"\s*([^()]+?)\s*(?:\((?:relaying|relay of)\s+([^)]+)\))?\s*$", sp)
                who, relay = (mm.group(1), mm.group(2)) if mm else (sp, None)
                slug = alias.get(who.strip().lower())
                if not slug:
                    unknown[who] += 1
                    continue
                ids = re.findall(r"M-\d{3}", r.get("objects", ""))
                per[slug].append({"source": title, "map": m.relative_to(ROOT).as_posix(), "relay": relay,
                                  "row": r, "objs": [(i, objs.get(i)) for i in ids]})
    OUT.mkdir(parents=True, exist_ok=True)
    idx = ["# People and their arguments", "",
           "Generated by `research/tools/people_pages.py` from the math map. Do not edit by hand.", "",
           "| Person | Side | Statements | Math objects | Open objects |", "|---|---|---|---|---|"]
    for slug in sorted(per, key=lambda s: (reg[s]["side"], reg[s]["name"])):
        p, items = reg[slug], per[slug]
        allobj = {i: o for it in items for i, o in it["objs"]}
        nopen = sum(1 for o in allobj.values() if o and o.get("status") != "resolved")
        idx.append(f"| [{p['name']}]({slug}.md) | {p['side']} | {len(items)} | {len(allobj)} | {nopen} |")
        out = [f"# {p['name']} ({p['side']})", "",
               "Generated by `research/tools/people_pages.py` from the math map. Do not edit by hand.", ""]
        for src in dict.fromkeys(it["source"] for it in items):
            out += [f"## {src}", ""]
            for it in [x for x in items if x["source"] == src]:
                r = it["row"]
                loc = r.get("locator", "")
                rel = f" *(relaying {it['relay']})*" if it["relay"] else ""
                out.append(f"- **{loc}**{rel} [{r.get('rh', '')}]: {r.get('quote', '')}")
                if r.get("steps"):
                    out.append(f"  - Steps: {r['steps']}")
                for i, o in it["objs"]:
                    if o:
                        rec = f"; record `{o['resolved_by']}`" if o.get("resolved_by") else ""
                        var = f"; variant of {o['variant_of']}" if o.get("variant_of") else ""
                        out.append(f"  - {i} ({o.get('kind')}, {o.get('status')}, settle by {o.get('resolution')}{var}{rec}): {str(o.get('statement'))[:160]}")
                    else:
                        out.append(f"  - {i} (not in objects file)")
                if r.get("arithmetic") and r["arithmetic"] not in ("n/a", "-"):
                    out.append(f"  - Arithmetic: {r['arithmetic']}")
            out.append("")
        (OUT / f"{slug}.md").write_text("\n".join(out) + "\n")
    if unknown:
        idx += ["", "Unregistered speakers (add them to `docs/research/math/people.yaml`): " +
                ", ".join(f"{k} ({v})" for k, v in unknown.most_common())]
    (OUT / "README.md").write_text("\n".join(idx) + "\n")
    print("\n".join(idx[4:]))


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
