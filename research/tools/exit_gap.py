"""Exit gap: the only list of work the autonomous team may start without the owner.

Reads docs/research/hierarchy.yaml (generated by lint_research.py) and
docs/research/gap-blockers.yaml (hand-kept: one row per open item, why it is open,
and the one next action). An item is OPEN while a load-bearing node is not
`reviewed` or has a `pending` verdict field, or while a manual X-* row in
gap-blockers.yaml is not marked done.

Usage (run from the repo root, research/.venv/bin/python -I):
  exit_gap.py                 table of open items, workable ones first
  exit_gap.py --workable      only items whose blocker is `none` (exit 3 if there are none)
  exit_gap.py --check ID      exit 0 if ID is an open item or a reserved tag, else 1
  exit_gap.py --lint          exit 1 if gap-blockers.yaml and hierarchy.yaml disagree
  exit_gap.py --audit REV     share of commits since REV per Gap trailer (on-gap / upkeep / owner / none)

Reserved Gap tags (not nodes): `upkeep` (lint/render/merge fixes that a failing gate
forced), `owner` (work the owner asked for; the commit body cites the D- id).
Read-only. Writes nothing.
"""
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
HIER = ROOT / "docs/research/hierarchy.yaml"
BLOCK = ROOT / "docs/research/gap-blockers.yaml"
RESERVED = {"upkeep", "owner"}
BLOCKERS = {"none", "after", "owner", "outside", "in-flight"}


def open_nodes():
    nodes = yaml.safe_load(HIER.read_text())["nodes"]
    out = {}
    for n in nodes:
        if not n.get("load_bearing"):
            continue
        v = n.get("verdicts", {}) or {}
        pend = [k for k, x in v.items() if x == "pending"]
        if n.get("status") != "reviewed" or pend:
            out[n["id"]] = {"status": n.get("status"), "pending": pend}
    return out


def load_blockers():
    rows = yaml.safe_load(BLOCK.read_text())["items"]
    return {r["id"]: r for r in rows}


def open_items():
    nodes, rows = open_nodes(), load_blockers()
    items = {}
    for nid, info in nodes.items():
        items[nid] = {**info, **rows.get(nid, {"blocker": "UNLISTED", "next": "add a row to gap-blockers.yaml"})}
    for rid, r in rows.items():
        if rid.startswith("X-") and not r.get("done"):
            items[rid] = {"status": "manual", "pending": [], **r}
    return items


def lint():
    nodes, rows = open_nodes(), load_blockers()
    errs = []
    for nid in nodes:
        if nid not in rows:
            errs.append(f"{nid}: open load-bearing node has no row in gap-blockers.yaml")
    for rid, r in rows.items():
        if not rid.startswith("X-") and rid not in nodes:
            errs.append(f"{rid}: row in gap-blockers.yaml but node is closed or not load-bearing; delete the row")
        if r.get("blocker") not in BLOCKERS:
            errs.append(f"{rid}: blocker must be one of {sorted(BLOCKERS)}")
        if not r.get("next"):
            errs.append(f"{rid}: no next action")
    for e in errs:
        print("ERROR", e)
    print(f"{len(errs)} errors")
    return 1 if errs else 0


def table(workable_only=False):
    items = open_items()
    order = {"none": 0, "in-flight": 1, "after": 2, "owner": 3, "outside": 4, "UNLISTED": 5}
    rows = sorted(items.items(), key=lambda kv: (order.get(kv[1].get("blocker"), 9), kv[0]))
    if workable_only:
        rows = [r for r in rows if r[1].get("blocker") == "none"]
    for iid, r in rows:
        pend = ",".join(r.get("pending", [])) or "-"
        print(f"{iid:8} {r.get('blocker',''):9} {r.get('status',''):9} pending={pend:22} next: {r.get('next','')}")
    n_work = sum(1 for _, r in items.items() if r.get("blocker") == "none")
    print(f"\n{len(items)} open, {n_work} workable now")
    if workable_only and not rows:
        print("Nothing workable. Do not invent work: post one owner card listing the blockers, then stop.")
        return 3
    return 0


def audit(rev):
    items = set(open_items()) | set(load_blockers())
    log = subprocess.run(
        ["git", "-C", str(ROOT), "log", "--no-merges", "--format=%H%x00%(trailers:key=Gap,valueonly,separator=%x2C)", f"{rev}..HEAD"],
        capture_output=True, text=True, check=True).stdout
    counts = {"on-gap": 0, "upkeep": 0, "owner": 0, "none": 0}
    for line in log.splitlines():
        if not line.strip():
            continue
        _, gap = line.split("\x00", 1)
        tags = [t.strip() for t in gap.split(",") if t.strip()]
        if not tags:
            counts["none"] += 1
        elif any(t in items for t in tags):
            counts["on-gap"] += 1
        elif "owner" in tags:
            counts["owner"] += 1
        elif "upkeep" in tags:
            counts["upkeep"] += 1
        else:
            counts["none"] += 1
    total = sum(counts.values()) or 1
    for k, v in counts.items():
        print(f"{k:7} {v:4}  {100*v/total:5.1f}%")
    return 0


def main(argv):
    if not argv:
        return table()
    if argv[0] == "--workable":
        return table(workable_only=True)
    if argv[0] == "--lint":
        return lint()
    if argv[0] == "--check" and len(argv) == 2:
        ok = argv[1] in RESERVED or argv[1] in open_items()
        return 0 if ok else 1
    if argv[0] == "--audit" and len(argv) == 2:
        return audit(argv[1])
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
